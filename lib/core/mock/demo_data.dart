String _mapMockNotifTypeToDb(String mockType) {
  switch (mockType) {
    case 'warning':
      return 'reminder';
    case 'success':
      return 'photo';
    case 'payout':
      return 'payout';
    case 'info':
    default:
      return 'milestone';
  }
}

