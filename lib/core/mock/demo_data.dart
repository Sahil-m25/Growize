/// Demo data adapter — converts the existing `mock_data.dart` into real
/// model objects flagged with `isDemo: true`.
///
/// Strategy:
///   - When the user is not signed in, providers show demo rows so the app
///     never feels empty during design review.
///   - When the user IS signed in but Supabase returns zero rows yet
///     (e.g. a new investor whose Zoho records haven't synced), demo rows
///     are still shown so the UI has substance — they're tagged isDemo.
///   - The moment a real row arrives, demo rows are filtered out by ID
///     prefix (`demo:` is reserved for them).
///
/// All demo IDs are prefixed `demo:` so they can never collide with real
/// UUIDs from Supabase.
