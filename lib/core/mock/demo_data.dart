List<Payout> demoPayouts({String? projectId}) {
  // Translate mock payouts (string IDs) to demo payouts.
  Iterable<MockPayout> source = mockPayouts;
  if (projectId != null) {
    final stripped = projectId.startsWith(demoIdPrefix)
        ? projectId.substring(demoIdPrefix.length)
        : projectId;
    source = source.where((p) => p.projectId == stripped);
  }
  return source
      .map((m) => Payout(
            id: '$demoIdPrefix${m.id}',
            amount: m.amount,
            projectId: '$demoIdPrefix${m.projectId}',
            projectName: m.projectName,
            status: m.status,
            date: m.date,
            utrRef: m.utrRef,
            isDemo: true,
          ))
      .toList();
}

