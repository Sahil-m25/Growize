/// Demo phases for a given mock project ID (gv|so|va).
/// When the projectId is a real UUID we just return [].
List<ProjectPhase> demoPhases(String projectId) {
  final stripped = projectId.startsWith(demoIdPrefix)
      ? projectId.substring(demoIdPrefix.length)
      : projectId;
  final source = mockPhaseMilestones[stripped] ?? const [];
  var i = 0;
  return source
      .map((m) => ProjectPhase(
            id: '$demoIdPrefix${stripped}_$i',
            projectId: '$demoIdPrefix$stripped',
            name: m.label,
            status: m.isDone ? 'done' : 'pending',
            sortOrder: i++,
            isDemo: true,
          ))
      .toList();
}

/// Strips demo rows from a list whenever any non-demo row is present.
/// Use this to merge real + demo without ever showing both for the same investor.
List<T> mergeWithDemo<T>(
  List<T> real,
  List<T> demo,
  bool Function(T) isDemoOf,
) {
  if (real.isEmpty) return demo;
  // We have real data — drop demo entirely, the user is past the empty state.
  return real.where((r) => !isDemoOf(r)).toList();
}

